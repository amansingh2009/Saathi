export type TranslationKey = keyof (typeof strings)["en"];

/**
 * Type-safe translation function with parameter interpolation support.
 * Example: t("en", "readyToHelp", { name: "Anita" }) -> "Anita is connected and ready to help."
 */
export function t(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const langStrings = strings[language] || strings.en;
  let text: string = (langStrings as Record<string, string>)[key] ?? strings.en[key] ?? key;

  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replaceAll(`{${pKey}}`, String(pVal));
    }
  }

  return text;
}
